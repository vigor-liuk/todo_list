import { test, expect } from './fixtures'

const task = (changes = {}) => ({ id: 'tracked', title: '阅读目标', note: '每天读一点', category: '课内', priority: '中', due: '2026-09-22T10:00', done: false, reminded: true, ...changes })
test.use({ timezoneId: 'Asia/Shanghai' })

test('start, reload, finish, review, export and reopen a task', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-09-22T09:00:00+08:00'))
  await page.goto('/')
  await page.evaluate(value => localStorage.setItem('little-day-tasks-v1', JSON.stringify(value)), [task()])
  await page.reload()
  await page.getByRole('button', { name: '开始：阅读目标', exact: true }).click()
  await expect(page.locator('.task-timing')).toContainText('09:00 — 进行中')
  await page.reload()
  await page.clock.setFixedTime(new Date('2026-09-22T09:30:00+08:00'))
  await expect(page.locator('.task-timing')).toContainText('30 分钟')
  await page.getByRole('button', { name: '结束并完成：阅读目标', exact: true }).click()
  await page.getByRole('button', { name: /时间回顾/ }).first().click()
  await page.getByRole('button', { name: '查看记录：阅读目标', exact: true }).click()
  await expect(page.locator('.record-detail')).toContainText('09:00 — 09:30 · 30 分钟')
  await expect(page.locator('.record-detail')).toContainText('原计划：2026-09-22 10:00')
  await expect(page.locator('.review-summary')).toContainText('当日完成 1 件')
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出任务', exact: true }).click()
  const download = await downloadEvent
  const stream = await download.createReadStream()
  const chunks = []
  for await (const chunk of stream!) chunks.push(chunk)
  const exported = JSON.parse(Buffer.concat(chunks).toString()).tasks[0]
  expect(exported.startedAt).toBe('2026-09-22T01:00:00.000Z')
  expect(exported.completedAt).toBe('2026-09-22T01:30:00.000Z')
  await page.reload()
  await page.getByRole('button', { name: /时间回顾/ }).first().click()
  await expect(page.locator('.execution-bar')).toHaveCount(1)
  await page.getByRole('button', { name: /全部任务/ }).click()
  await page.getByRole('button', { name: '取消完成：阅读目标', exact: true }).click()
  await expect(page.getByRole('button', { name: '开始：阅读目标', exact: true })).toBeVisible()
  await page.getByRole('button', { name: /时间回顾/ }).first().click()
  await expect(page.locator('.execution-bar')).toHaveCount(0)
})

